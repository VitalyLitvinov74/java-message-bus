package io.github.vitalylitvinov74.messaging;

import an.awesome.pipelinr.Command;

import java.util.concurrent.CompletionStage;

/**
 * Единственная точка, через которую прикладной код отправляет сообщения. Команды и запросы
 * исполняются в этом же процессе ровно одним обработчиком. Событие получают местные
 * обработчики, а событие с {@link Publish} уходит ещё и в Kafka.
 *
 * Приём из Kafka сюда не входит: его делает {@code @KafkaListener} сервиса, который
 * передаёт принятое сообщение в эту же шину.
 */
public interface MessageBus {

    /** Исполняет команду и возвращает результат её обработчика. */
    <R, C extends Command<R>> R send(C command);

    /** Исполняет запрос и возвращает результат его обработчика. */
    <R, Q extends Query<R>> R ask(Q query);

    /**
     * Отдаёт событие местным обработчикам, затем публикует его в топик из {@link Publish}.
     *
     * Ошибка местного обработчика или неверная разметка события бросается сразу, и в Kafka
     * ничего не уходит. Отказ брокера приходит только через результат: он завершается, когда
     * брокер подтвердил запись, или с ошибкой. Событие без {@link Publish} даёт уже
     * завершённый результат.
     */
    CompletionStage<Void> publish(DomainEvent event);
}
